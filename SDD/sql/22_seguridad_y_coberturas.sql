CREATE TABLE auditoria_seguridad (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha timestamptz NOT NULL DEFAULT now(), usuario_id bigint,
 evento varchar(100) NOT NULL, recurso varchar(300) NOT NULL,
 estado integer NOT NULL, origen_hash varchar(64) NOT NULL DEFAULT ''
);
CREATE INDEX auditoria_seguridad_fecha_idx ON auditoria_seguridad(fecha);
CREATE FUNCTION impedir_modificacion_auditoria() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'El registro de seguridad es inmutable'; END $$;
CREATE TRIGGER auditoria_inmutable BEFORE UPDATE OR DELETE ON auditoria_seguridad
 FOR EACH ROW EXECUTE FUNCTION impedir_modificacion_auditoria();
CREATE TABLE limites_acceso (clave varchar(64) PRIMARY KEY, inicio timestamptz NOT NULL, intentos integer NOT NULL CHECK(intentos > 0));
CREATE TABLE documentos_polizas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 poliza_id bigint NOT NULL REFERENCES polizas(id),
 documento_id bigint NOT NULL REFERENCES documentos_generales(id),
 vinculado_por_id bigint NOT NULL REFERENCES funcionarios(id),
 creado_en timestamptz NOT NULL DEFAULT now(), UNIQUE(poliza_id,documento_id)
);
CREATE TABLE contextos_cobertura (
 conversacion_id bigint PRIMARY KEY REFERENCES conversaciones(id),
 cliente_id bigint NOT NULL REFERENCES clientes(id),
 creado_en timestamptz NOT NULL DEFAULT now(), expira_en timestamptz NOT NULL,
 poliza_id bigint REFERENCES polizas(id), pregunta text NOT NULL DEFAULT '',
 CHECK(expira_en > creado_en)
);
COMMIT;
