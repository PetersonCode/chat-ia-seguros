-- Pantalla de vencimientos y envío manual desde el panel. Después de 22.
-- Aditivo e idempotente: no genera avisos ni modifica pólizas/cuotas.
BEGIN;
CREATE TABLE IF NOT EXISTS recordatorios_polizas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 poliza_id bigint NOT NULL REFERENCES polizas(id),
 contacto_id bigint NOT NULL REFERENCES contactos_whatsapp(id),
 funcionario_id bigint NOT NULL REFERENCES funcionarios(id),
 mensaje_id bigint UNIQUE REFERENCES mensajes(id) ON DELETE SET NULL,
 fecha_aviso date NOT NULL, fecha_vencimiento date NOT NULL,
 saldo_pendiente numeric(12,2) NOT NULL, texto text NOT NULL,
 canal text NOT NULL CHECK (canal IN ('api','manual')),
 creado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(poliza_id, contacto_id, fecha_aviso)
);
CREATE INDEX IF NOT EXISTS recordatorios_polizas_fecha_idx
 ON recordatorios_polizas(poliza_id, creado_en DESC);
COMMIT;
