-- Una fila por consulta, con color de alerta (rojo / naranja / amarillo / verde)
CREATE VIEW v_consultas_supervision AS
SELECT c.id,
       c.codigo_caso,
       c.fecha_hora,
       cw.numero              AS whatsapp,
       cl.apellido || ', ' || cl.nombre AS cliente,
       tc.codigo              AS tipo_consulta,
       tc.politica,
       c.mensaje_usuario,
       c.respuesta_bot,
       c.estado,
       f.nombre               AS funcionario_asignado,
       COALESCE(a.alertas_abiertas, 0) AS alertas_abiertas,
       a.severidad_maxima,
       CASE a.severidad_maxima
            WHEN 'critica' THEN 'rojo'
            WHEN 'alta'    THEN 'naranja'
            WHEN 'media'   THEN 'amarillo'
            WHEN 'baja'    THEN 'amarillo'
            ELSE 'verde'
       END                    AS color,
       (c.estado = 'cerrado' AND COALESCE(a.alertas_abiertas, 0) > 0) AS cerrado_con_alerta,
       c.revisado_en IS NOT NULL AS revisada
FROM consultas_bot c
JOIN tipos_consulta tc           ON tc.id = c.tipo_consulta_id
LEFT JOIN contactos_whatsapp cw  ON cw.id = c.contacto_id
LEFT JOIN clientes cl            ON cl.id = cw.cliente_id
LEFT JOIN funcionarios f         ON f.id = c.funcionario_asignado_id
LEFT JOIN LATERAL (
    SELECT count(*) AS alertas_abiertas,
           (ARRAY['baja','media','alta','critica'])[max(CASE al.severidad
                WHEN 'baja' THEN 1 WHEN 'media' THEN 2 WHEN 'alta' THEN 3 ELSE 4 END)] AS severidad_maxima
    FROM alertas al
    WHERE al.consulta_id = c.id AND al.estado IN ('abierta', 'en_revision')
) a ON true;

-- Datos reales de cada póliza, para contrastar contra lo que dijo el bot
CREATE VIEW v_polizas_resumen AS
SELECT p.id AS poliza_id,
       p.numero_poliza,
       cl.apellido || ', ' || cl.nombre AS cliente,
       cl.dni,
       ts.nombre AS tipo_seguro,
       p.cobertura,
       p.estado,
       p.fecha_vencimiento,
       COALESCE(sum(q.importe) FILTER (WHERE q.estado IN ('pendiente', 'vencida')), 0) AS saldo_pendiente,
       min(q.vencimiento) FILTER (WHERE q.estado IN ('pendiente', 'vencida'))          AS proximo_vencimiento_pago
FROM polizas p
JOIN clientes cl     ON cl.id = p.cliente_id
JOIN tipos_seguro ts ON ts.id = p.tipo_seguro_id
LEFT JOIN cuotas q   ON q.poliza_id = p.id
GROUP BY p.id, cl.id, ts.id;
