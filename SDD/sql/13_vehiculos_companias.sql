-- =====================================================================
-- P1 · Vehículos y compañías
-- Depende de: 01_schema.sql (clientes, polizas). Se aplica después de
-- 12_tipos_de_charla.sql; el orden respecto de 22_seguridad_y_coberturas.sql
-- es indistinto. Aditivo e idempotente: se puede correr más de una vez y no
-- toca datos existentes.
--
--   companias : quién emite la póliza y cuánta comisión deja.
--   vehiculos : el bien asegurado como dato (patente única), no como texto libre.
--   polizas   : + vehiculo_id, + compania_id, + comision_pct. `bien_asegurado`
--               se conserva: las pólizas viejas no se tocan.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS companias (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       text NOT NULL CHECK (btrim(nombre) <> ''),
    comision_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (comision_pct BETWEEN 0 AND 100),
    activa       boolean NOT NULL DEFAULT true
);
-- Único sin distinguir mayúsculas ni espacios: "La Caja" = "la  caja" = "LACAJA".
CREATE UNIQUE INDEX IF NOT EXISTS companias_nombre_uk
    ON companias ((lower(regexp_replace(nombre, '\s+', '', 'g'))));

CREATE TABLE IF NOT EXISTS vehiculos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       bigint NOT NULL REFERENCES clientes (id),
    -- Auto viejo (ABC123), auto nuevo (AB123CD), moto vieja (123ABC), moto nueva (A123BCD).
    patente          text NOT NULL UNIQUE
                     CHECK (patente ~ '^([A-Z]{3}[0-9]{3}|[A-Z]{2}[0-9]{3}[A-Z]{2}|[0-9]{3}[A-Z]{3}|[A-Z][0-9]{3}[A-Z]{3})$'),
    marca            text NOT NULL CHECK (btrim(marca) <> ''),
    modelo           text NOT NULL CHECK (btrim(modelo) <> ''),
    anio             smallint NOT NULL
                     CHECK (anio BETWEEN 1950 AND EXTRACT(YEAR FROM CURRENT_DATE)::int + 1),
    uso              text NOT NULL DEFAULT 'particular'
                     CHECK (uso IN ('particular', 'comercial', 'remis_taxi', 'carga')),
    chasis           text,
    valor_asegurado  numeric(12,2) CHECK (valor_asegurado > 0),
    activo           boolean NOT NULL DEFAULT true,
    creado_en        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS vehiculos_cliente_idx ON vehiculos (cliente_id);

ALTER TABLE polizas
    ADD COLUMN IF NOT EXISTS vehiculo_id  bigint REFERENCES vehiculos (id),
    ADD COLUMN IF NOT EXISTS compania_id  bigint REFERENCES companias (id),
    ADD COLUMN IF NOT EXISTS comision_pct numeric(5,2) CHECK (comision_pct BETWEEN 0 AND 100);
CREATE INDEX IF NOT EXISTS polizas_vehiculo_idx ON polizas (vehiculo_id);
CREATE INDEX IF NOT EXISTS polizas_compania_idx ON polizas (compania_id);

COMMIT;
