-- =====================================================================
-- Adjuntos privados de expedientes de siniestros
-- Uso: después de 07_expediente_siniestros.sql.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS siniestro_adjuntos (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siniestro_id          bigint NOT NULL REFERENCES siniestros (id),
    clave_almacenamiento  text NOT NULL UNIQUE CHECK (
                              clave_almacenamiento ~
                              '^siniestros/[0-9]+/[0-9a-f]{32}\.(jpg|png|webp)$'
                          ),
    content_type          text NOT NULL CHECK (
                              content_type IN ('image/jpeg', 'image/png', 'image/webp')
                          ),
    tamano                integer NOT NULL CHECK (tamano BETWEEN 1 AND 10485760),
    sha256                text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    origen                text NOT NULL CHECK (origen IN ('panel', 'whatsapp')),
    mensaje_origen_id     bigint UNIQUE REFERENCES mensajes (id),
    creado_por_id         bigint REFERENCES funcionarios (id),
    creado_en             timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (origen = 'panel' AND creado_por_id IS NOT NULL AND mensaje_origen_id IS NULL)
        OR
        (origen = 'whatsapp' AND creado_por_id IS NULL AND mensaje_origen_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS siniestro_adjuntos_siniestro_fecha_idx
    ON siniestro_adjuntos (siniestro_id, creado_en, id);

CREATE OR REPLACE FUNCTION siniestro_adjunto_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    poliza_cliente_id bigint;
    funcionario_activo boolean;
    mensaje_entrante boolean;
    contacto_cliente_id bigint;
BEGIN
    SELECT p.cliente_id
    INTO poliza_cliente_id
    FROM siniestros s
    JOIN polizas p ON p.id = s.poliza_id
    WHERE s.id = NEW.siniestro_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El siniestro asociado no existe';
    END IF;

    IF NEW.origen = 'panel' THEN
        SELECT activo INTO funcionario_activo
        FROM funcionarios
        WHERE id = NEW.creado_por_id;
        IF NOT FOUND OR NOT funcionario_activo THEN
            RAISE EXCEPTION 'El adjunto requiere un funcionario activo';
        END IF;
    ELSE
        SELECT (m.direccion = 'entrante' AND m.emisor = 'cliente'), cw.cliente_id
        INTO mensaje_entrante, contacto_cliente_id
        FROM mensajes m
        JOIN conversaciones c ON c.id = m.conversacion_id
        JOIN contactos_whatsapp cw ON cw.id = c.contacto_id
        WHERE m.id = NEW.mensaje_origen_id;
        IF NOT FOUND OR NOT mensaje_entrante OR
           contacto_cliente_id IS DISTINCT FROM poliza_cliente_id THEN
            RAISE EXCEPTION 'El adjunto no pertenece al cliente del siniestro';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS siniestro_adjunto_validar_trigger ON siniestro_adjuntos;
CREATE TRIGGER siniestro_adjunto_validar_trigger
BEFORE INSERT ON siniestro_adjuntos
FOR EACH ROW
EXECUTE FUNCTION siniestro_adjunto_validar();

CREATE OR REPLACE FUNCTION siniestro_adjunto_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Los metadatos de adjuntos de siniestros son inmutables';
END;
$$;

DROP TRIGGER IF EXISTS siniestro_adjunto_inmutable_trigger ON siniestro_adjuntos;
CREATE TRIGGER siniestro_adjunto_inmutable_trigger
BEFORE UPDATE ON siniestro_adjuntos
FOR EACH ROW
EXECUTE FUNCTION siniestro_adjunto_inmutable();

COMMIT;
