-- Imágenes y videos que el cliente manda por el chat: se guardan en el almacenamiento
-- privado para que quien atiende (p. ej. una denuncia de siniestro) pueda descargarlos.
BEGIN;
CREATE TABLE IF NOT EXISTS mensaje_adjuntos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id BIGINT NOT NULL UNIQUE REFERENCES mensajes(id) ON DELETE CASCADE,
    clave_almacenamiento TEXT NOT NULL UNIQUE
        CHECK (clave_almacenamiento ~ '^chat/[0-9]+/[0-9a-f]{32}\.(jpg|png|webp|mp4|3gp)$'),
    nombre_archivo TEXT NOT NULL CHECK (btrim(nombre_archivo) <> ''),
    content_type TEXT NOT NULL
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'video/3gpp')),
    tamano INTEGER NOT NULL CHECK (tamano >= 1 AND tamano <= 16777216),
    sha256 TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE trabajos_whatsapp DROP CONSTRAINT IF EXISTS trabajos_whatsapp_tipo_check;
ALTER TABLE trabajos_whatsapp ADD CONSTRAINT trabajos_whatsapp_tipo_check
    CHECK (tipo IN ('texto', 'imagen', 'aviso_formato', 'video'));
COMMIT;
