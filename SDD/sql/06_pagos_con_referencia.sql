BEGIN;

CREATE TABLE IF NOT EXISTS pagos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia     text NOT NULL UNIQUE
                   CHECK (length(btrim(referencia)) BETWEEN 1 AND 100),
    cuota_id       bigint NOT NULL UNIQUE REFERENCES cuotas (id),
    importe        numeric(12,2) NOT NULL CHECK (importe > 0),
    fecha_pago     date NOT NULL,
    responsable_id bigint NOT NULL REFERENCES funcionarios (id)
);

CREATE OR REPLACE FUNCTION aplicar_pago_cuota()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    cuota cuotas%ROWTYPE;
BEGIN
    SELECT * INTO cuota
    FROM cuotas
    WHERE id = NEW.cuota_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La cuota del pago no existe.';
    END IF;
    IF cuota.estado NOT IN ('pendiente', 'vencida') THEN
        RAISE EXCEPTION 'La cuota del pago ya no está impaga.';
    END IF;
    IF NEW.importe <> cuota.importe THEN
        RAISE EXCEPTION 'El pago debe cubrir el importe completo de la cuota.';
    END IF;

    UPDATE cuotas
    SET estado = 'pagada',
        fecha_pago = NEW.fecha_pago,
        importe_pagado = NEW.importe
    WHERE id = NEW.cuota_id;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS pagos_aplicar_cuota ON pagos;
CREATE TRIGGER pagos_aplicar_cuota
BEFORE INSERT ON pagos
FOR EACH ROW
EXECUTE FUNCTION aplicar_pago_cuota();

COMMIT;
