-- =====================================================================
-- Historial auditable y control de transiciones del expediente de siniestros
-- Uso: después de 06_pagos_con_referencia.sql.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS siniestro_historial (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siniestro_id     bigint NOT NULL REFERENCES siniestros (id),
    estado_anterior  text CHECK (estado_anterior IN
                         ('denunciado', 'en_evaluacion', 'aprobado', 'rechazado', 'cerrado')),
    estado_nuevo     text NOT NULL CHECK (estado_nuevo IN
                         ('denunciado', 'en_evaluacion', 'aprobado', 'rechazado', 'cerrado')),
    motivo           text NOT NULL CHECK (length(btrim(motivo)) >= 3),
    responsable_id   bigint NOT NULL REFERENCES funcionarios (id),
    fecha            timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (estado_anterior IS NULL AND estado_nuevo = 'denunciado')
        OR estado_anterior IS NOT NULL
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS siniestro_historial_denuncia_unica_idx
    ON siniestro_historial (siniestro_id)
    WHERE estado_anterior IS NULL;
CREATE INDEX IF NOT EXISTS siniestro_historial_siniestro_fecha_idx
    ON siniestro_historial (siniestro_id, fecha, id);

CREATE OR REPLACE FUNCTION siniestro_historial_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    estado_actual text;
    funcionario_activo boolean;
    funcionario_aprobador boolean;
BEGIN
    SELECT activo, puede_aprobar
    INTO funcionario_activo, funcionario_aprobador
    FROM funcionarios
    WHERE id = NEW.responsable_id
    FOR UPDATE;
    IF NOT FOUND OR NOT funcionario_activo THEN
        RAISE EXCEPTION 'El registro requiere un funcionario activo';
    END IF;

    SELECT estado INTO estado_actual
    FROM siniestros
    WHERE id = NEW.siniestro_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El siniestro no existe';
    END IF;

    IF NEW.estado_anterior IS NULL THEN
        IF NEW.estado_nuevo <> 'denunciado' OR estado_actual <> 'denunciado' THEN
            RAISE EXCEPTION 'El historial inicial solo puede registrar una denuncia nueva';
        END IF;
    ELSE
        IF NOT funcionario_aprobador THEN
            RAISE EXCEPTION 'La decisión requiere un funcionario activo con permiso de aprobación';
        END IF;
        IF NEW.estado_anterior <> estado_actual OR NOT (
            (NEW.estado_anterior = 'denunciado' AND NEW.estado_nuevo = 'en_evaluacion')
            OR (NEW.estado_anterior = 'en_evaluacion' AND NEW.estado_nuevo IN ('aprobado', 'rechazado'))
            OR (NEW.estado_anterior IN ('aprobado', 'rechazado') AND NEW.estado_nuevo = 'cerrado')
        ) THEN
            RAISE EXCEPTION 'Transición de estado de siniestro no permitida';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS siniestro_historial_validar_trigger ON siniestro_historial;
CREATE TRIGGER siniestro_historial_validar_trigger
BEFORE INSERT ON siniestro_historial
FOR EACH ROW
EXECUTE FUNCTION siniestro_historial_validar();

CREATE OR REPLACE FUNCTION siniestro_estado_exige_historial()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado <> OLD.estado THEN
        IF NOT (
            (OLD.estado = 'denunciado' AND NEW.estado = 'en_evaluacion')
            OR (OLD.estado = 'en_evaluacion' AND NEW.estado IN ('aprobado', 'rechazado'))
            OR (OLD.estado IN ('aprobado', 'rechazado') AND NEW.estado = 'cerrado')
        ) THEN
            RAISE EXCEPTION 'Transición de estado de siniestro no permitida';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM siniestro_historial
            WHERE siniestro_id = OLD.id
              AND estado_anterior = OLD.estado
              AND estado_nuevo = NEW.estado
        ) THEN
            RAISE EXCEPTION 'El cambio de estado requiere un registro de decisión';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS siniestro_estado_exige_historial_trigger ON siniestros;
CREATE TRIGGER siniestro_estado_exige_historial_trigger
BEFORE UPDATE OF estado ON siniestros
FOR EACH ROW
EXECUTE FUNCTION siniestro_estado_exige_historial();

CREATE OR REPLACE FUNCTION siniestro_historial_aplicar_estado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado_anterior IS NOT NULL THEN
        UPDATE siniestros
        SET estado = NEW.estado_nuevo
        WHERE id = NEW.siniestro_id
          AND estado = NEW.estado_anterior;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'El estado del siniestro cambió durante la decisión';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS siniestro_historial_aplicar_estado_trigger ON siniestro_historial;
CREATE TRIGGER siniestro_historial_aplicar_estado_trigger
AFTER INSERT ON siniestro_historial
FOR EACH ROW
EXECUTE FUNCTION siniestro_historial_aplicar_estado();

CREATE OR REPLACE FUNCTION siniestro_historial_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'El historial de siniestros es inmutable';
END;
$$;

DROP TRIGGER IF EXISTS siniestro_historial_inmutable_trigger ON siniestro_historial;
CREATE TRIGGER siniestro_historial_inmutable_trigger
BEFORE UPDATE OR DELETE ON siniestro_historial
FOR EACH ROW
EXECUTE FUNCTION siniestro_historial_inmutable();

COMMIT;
