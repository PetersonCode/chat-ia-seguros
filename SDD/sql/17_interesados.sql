-- =====================================================================
-- P5 · Embudo de interesados y cotizaciones
-- Depende de: 01_schema.sql (funcionarios, clientes, polizas),
-- 03_whatsapp.sql (contactos_whatsapp) y 13_vehiculos_companias.sql
-- (companias). Aditivo e idempotente: se puede correr más de una vez y no
-- toca datos existentes.
--
--   interesados          : quien todavía no es cliente (o lo es y pide otro
--                          seguro: venta cruzada), con dueño y próximo contacto.
--   interesado_historial : cada cambio de etapa y cada gestión, con quién y cuándo.
--   cotizaciones         : lo que cotiza cada compañía, para un interesado
--                          (venta nueva) o para una póliza (renovación).
--   tipos_aviso          : suma los dos hitos de seguimiento SI el motor de
--                          avisos (P2, 14_avisos.sql) ya está aplicado. Si no,
--                          no hace nada: el orden entre P2 y P5 es indistinto.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS interesados (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          text NOT NULL CHECK (btrim(nombre) <> ''),
    apellido        text,
    contacto_id     bigint REFERENCES contactos_whatsapp (id),
    cliente_id      bigint REFERENCES clientes (id),
    origen          text NOT NULL
                    CHECK (origen IN ('whatsapp', 'instagram', 'facebook', 'web',
                                      'recomendacion', 'llamado', 'otro')),
    estado          text NOT NULL DEFAULT 'consulta'
                    CHECK (estado IN ('consulta', 'cotizando', 'documentacion',
                                      'emitida', 'perdida')),
    responsable_id  bigint REFERENCES funcionarios (id),
    proximo_contacto date,
    motivo_perdida  text,
    -- dni, patente, marca, modelo, anio, uso, localidad, tipo_seguro
    datos           jsonb NOT NULL DEFAULT '{}'::jsonb
                    CONSTRAINT interesados_datos_objeto CHECK (jsonb_typeof(datos) = 'object'),
    creado_en       timestamptz NOT NULL DEFAULT now(),
    actualizado_en  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT interesados_perdida_exige_motivo
        CHECK (estado <> 'perdida' OR length(btrim(coalesce(motivo_perdida, ''))) >= 3),
    CONSTRAINT interesados_emitida_exige_cliente
        CHECK (estado <> 'emitida' OR cliente_id IS NOT NULL)
);
-- Un número de WhatsApp tiene a lo sumo un interesado abierto (ni emitida ni perdida).
CREATE UNIQUE INDEX IF NOT EXISTS interesados_un_abierto_por_contacto_uk
    ON interesados (contacto_id)
    WHERE contacto_id IS NOT NULL AND estado NOT IN ('emitida', 'perdida');
CREATE INDEX IF NOT EXISTS interesados_estado_idx ON interesados (estado);
CREATE INDEX IF NOT EXISTS interesados_responsable_idx ON interesados (responsable_id);
CREATE INDEX IF NOT EXISTS interesados_contacto_idx ON interesados (contacto_id);

CREATE TABLE IF NOT EXISTS interesado_historial (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interesado_id    bigint NOT NULL REFERENCES interesados (id),
    estado_anterior  text CHECK (estado_anterior IN
                         ('consulta', 'cotizando', 'documentacion', 'emitida', 'perdida')),
    estado_nuevo     text NOT NULL CHECK (estado_nuevo IN
                         ('consulta', 'cotizando', 'documentacion', 'emitida', 'perdida')),
    nota             text,
    funcionario_id   bigint REFERENCES funcionarios (id),
    fecha            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS interesado_historial_interesado_idx
    ON interesado_historial (interesado_id, fecha, id);

CREATE TABLE IF NOT EXISTS cotizaciones (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interesado_id   bigint REFERENCES interesados (id),
    poliza_id       bigint REFERENCES polizas (id),
    compania_id     bigint NOT NULL REFERENCES companias (id),
    cobertura       text NOT NULL CHECK (cobertura IN ('basica', 'intermedia', 'total')),
    prima_mensual   numeric(12,2) NOT NULL CHECK (prima_mensual > 0),
    vigencia_hasta  date,
    elegida         boolean NOT NULL DEFAULT false,
    notas           text,
    creada_por_id   bigint NOT NULL REFERENCES funcionarios (id),
    creada_en       timestamptz NOT NULL DEFAULT now(),
    -- Una o la otra, nunca ninguna ni las dos.
    CONSTRAINT cotizaciones_interesado_o_poliza
        CHECK ((interesado_id IS NULL) <> (poliza_id IS NULL))
);
-- Una sola elegida por interesado y una sola por póliza.
CREATE UNIQUE INDEX IF NOT EXISTS cotizaciones_una_elegida_por_interesado_uk
    ON cotizaciones (interesado_id) WHERE elegida AND interesado_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS cotizaciones_una_elegida_por_poliza_uk
    ON cotizaciones (poliza_id) WHERE elegida AND poliza_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS cotizaciones_interesado_idx ON cotizaciones (interesado_id);
CREATE INDEX IF NOT EXISTS cotizaciones_poliza_idx ON cotizaciones (poliza_id);

-- Catálogo de avisos de P2: solo si la tabla ya existe.
DO $$
BEGIN
    IF to_regclass('tipos_aviso') IS NOT NULL THEN
        INSERT INTO tipos_aviso (codigo, nombre, prioridad, activo) VALUES
            ('seguimiento_cotizacion_2d', 'Seguimiento de cotización (2 días)', 4, true),
            ('seguimiento_cotizacion_5d', 'Seguimiento de cotización (5 días)', 4, true)
        ON CONFLICT (codigo) DO UPDATE
            SET nombre = EXCLUDED.nombre,
                prioridad = EXCLUDED.prioridad,
                activo = EXCLUDED.activo;
    END IF;
END
$$;

COMMIT;
