-- =====================================================================
-- Fuentes documentales generales para consulta local.
-- Uso: después de 08_adjuntos_siniestros.sql.
-- No contiene ni referencia documentos privados de clientes.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS documentos_generales (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          text NOT NULL CHECK (length(trim(titulo)) BETWEEN 1 AND 300),
    version         text NOT NULL CHECK (length(trim(version)) BETWEEN 1 AND 100),
    referencia      text NOT NULL CHECK (length(trim(referencia)) BETWEEN 1 AND 1000),
    estado          text NOT NULL DEFAULT 'borrador'
                    CHECK (estado IN ('borrador', 'aprobado', 'retirado')),
    creado_por_id   bigint NOT NULL REFERENCES funcionarios (id),
    creado_en       timestamptz NOT NULL DEFAULT now(),
    aprobado_por_id bigint REFERENCES funcionarios (id),
    aprobado_en     timestamptz,
    retirado_por_id bigint REFERENCES funcionarios (id),
    retirado_en     timestamptz,
    UNIQUE (titulo, version),
    CHECK (
        (estado = 'borrador' AND aprobado_por_id IS NULL AND aprobado_en IS NULL
            AND retirado_por_id IS NULL AND retirado_en IS NULL)
        OR
        (estado = 'aprobado' AND aprobado_por_id IS NOT NULL AND aprobado_en IS NOT NULL
            AND retirado_por_id IS NULL AND retirado_en IS NULL)
        OR
        (estado = 'retirado' AND aprobado_por_id IS NOT NULL AND aprobado_en IS NOT NULL
            AND retirado_por_id IS NOT NULL AND retirado_en IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS documentos_generales_fragmentos (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id bigint NOT NULL REFERENCES documentos_generales (id),
    orden        integer NOT NULL CHECK (orden > 0),
    texto        text NOT NULL CHECK (length(trim(texto)) > 0),
    UNIQUE (documento_id, orden)
);

CREATE INDEX IF NOT EXISTS documentos_generales_estado_idx
    ON documentos_generales (estado, titulo);
CREATE INDEX IF NOT EXISTS documentos_generales_fragmentos_documento_idx
    ON documentos_generales_fragmentos (documento_id, orden);

COMMIT;
