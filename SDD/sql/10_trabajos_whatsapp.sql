-- Cola durable de procesamiento entrante y reintentos de envio WhatsApp.
-- Aplicar despues de 09_documentos_generales.sql.
BEGIN;

ALTER TABLE mensajes
    ADD COLUMN intentos_envio smallint NOT NULL DEFAULT 0
        CHECK (intentos_envio >= 0),
    ADD COLUMN proximo_intento_envio timestamptz,
    ADD COLUMN respuesta_a_id bigint UNIQUE REFERENCES mensajes (id);

CREATE TABLE trabajos_whatsapp (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id bigint NOT NULL UNIQUE REFERENCES mensajes (id),
    tipo text NOT NULL CHECK (tipo IN ('texto', 'imagen', 'aviso_formato')),
    estado text NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'procesando', 'completado', 'fallido')),
    intentos smallint NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    disponible_en timestamptz NOT NULL DEFAULT now(),
    tomado_en timestamptz,
    completado_en timestamptz,
    ultimo_error text,
    CHECK (
        (estado = 'procesando' AND tomado_en IS NOT NULL)
        OR estado <> 'procesando'
    ),
    CHECK (
        (estado = 'completado' AND completado_en IS NOT NULL)
        OR estado <> 'completado'
    )
);

CREATE INDEX trabajos_whatsapp_disponibles_idx
    ON trabajos_whatsapp (disponible_en, id)
    WHERE estado IN ('pendiente', 'procesando');

CREATE INDEX mensajes_reintento_envio_idx
    ON mensajes (proximo_intento_envio, conversacion_id)
    WHERE estado_envio = 'fallido' AND proximo_intento_envio IS NOT NULL;

COMMIT;
